const DICTS: Record<Lang, Dict> = { ru, en, es };

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string>,
): string {
  let s = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

/** Non-hook translator for use outside React (agent loop, store, helpers). */
export function tr(key: string, vars?: Record<string, string>): string {
  return translate(useStore.getState().lang, key, vars);
}

/** Hook: returns a `t(key, vars?)` bound to the current language. */
export function useT() {
  const lang = useStore((s) => s.lang);
  return (key: string, vars?: Record<string, string>) =>
    translate(lang, key, vars);
}
